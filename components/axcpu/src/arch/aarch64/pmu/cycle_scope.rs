//! Bounded borrowing of an otherwise unused cycle counter.

use core::{arch::asm, marker::PhantomData};

use super::{EventConfig, Pmu, isb};

const CYCLE_BIT: u64 = 1 << 31;
const PMCR_CONTROL: u64 = 0xf8; // D/X/DP/LC/LP; never P/C/E.

/// A temporary cycle-counter scope could not be admitted. No state was written.
#[derive(Clone, Copy, Debug, Eq, PartialEq, thiserror::Error)]
pub enum CycleScopeError {
    /// Some local counter, interrupt, global counting or EL0 access is enabled.
    #[error("the local PMU is not idle")]
    Busy,
    /// This PMU version has not been qualified for state-preserving borrowing.
    #[error("temporary cycle counting does not support this PMU version")]
    UnsupportedVersion,
    /// Only the dedicated cycle event, 0x11, is valid for this scope.
    #[error("temporary cycle counting requires event 0x11")]
    InvalidConfiguration,
}

/// Read-only access to a temporarily enabled, undivided 64-bit cycle counter.
/// The owning scope restores the original register state before returning.
pub struct CycleCounter<'a> {
    pmcr: u64,
    filter: u64,
    value: u64,
    overflowed: bool,
    _owner: PhantomData<&'a mut Pmu>,
}

impl CycleCounter<'_> {
    /// Returns the full cycle count after instruction synchronization.
    /// Privilege filtering and debug restrictions still apply.
    pub fn read(&self) -> u64 {
        isb();
        read_reg!("PMCCNTR_EL0")
    }
}

impl Pmu {
    /// Borrows an idle PMU's cycle counter for a bounded read-only callback.
    /// Counts every cycle at the selected privilege levels; temporarily disables
    /// event export. Preserves the full old cycle value, filter, overflow flags,
    /// global control and all programmable-counter state. Requires PMUv3,
    /// PMUv3p1, PMUv3p4 or PMUv3p5 (version encodings 1, 4, 5, 6).
    ///
    /// The callback's return value, including an `Err`, does not bypass restore.
    /// Rust unwinding also restores state; abort or machine reset cannot do so.
    ///
    /// # Safety
    /// The caller must have withdrawn every local PMU user, including guests,
    /// IRQ handlers and external debug agents. Idle register checks alone do
    /// not prove ownership. Keep this CPU pinned with IRQs excluded throughout;
    /// the callback must not block, enable IRQs, migrate, reconfigure PMU state
    /// through another path, or establish another PMU session. Higher exception
    /// levels must permit these accesses and must not modify the borrowed state.
    pub unsafe fn with_temporary_cycle_counter<R>(
        &mut self,
        config: EventConfig,
        operation: impl FnOnce(&CycleCounter<'_>) -> R,
    ) -> Result<R, CycleScopeError> {
        if !matches!(self.info.version, 1 | 4 | 5 | 6) {
            return Err(CycleScopeError::UnsupportedVersion);
        }
        if config.event != 0x11 {
            return Err(CycleScopeError::InvalidConfiguration);
        }
        let pmcr = read_reg!("PMCR_EL0");
        let enabled = read_reg!("PMCNTENSET_EL0") & self.implemented_mask();
        let interrupts = read_reg!("PMINTENSET_EL1") & self.implemented_mask();
        let users = read_reg!("PMUSERENR_EL0");
        if pmcr & 1 != 0 || enabled != 0 || interrupts != 0 || users != 0 {
            return Err(CycleScopeError::Busy);
        }
        let counter = CycleCounter {
            pmcr: pmcr & PMCR_CONTROL,
            filter: read_reg!("PMCCFILTR_EL0"),
            value: read_reg!("PMCCNTR_EL0"),
            overflowed: read_reg!("PMOVSCLR_EL0") & CYCLE_BIT != 0,
            _owner: PhantomData,
        };
        // Retain DP/LP, select long cycles, disable divider and event export.
        // Admission excludes newer PMCR fields; P/C are always written zero.
        write_reg!("PMCR_EL0", (counter.pmcr & 0xa0) | (1 << 6));
        write_reg!("PMCCFILTR_EL0", config.filter_bits());
        write_reg!("PMCCNTR_EL0", 0);
        isb();
        write_reg!("PMCNTENSET_EL0", CYCLE_BIT);
        write_reg!("PMCR_EL0", (counter.pmcr & 0xa0) | (1 << 6) | 1);
        isb();
        Ok(operation(&counter))
    }
}

impl Drop for CycleCounter<'_> {
    fn drop(&mut self) {
        write_reg!("PMCR_EL0", (self.pmcr & 0xa0) | (1 << 6));
        isb();
        write_reg!("PMCNTENCLR_EL0", CYCLE_BIT);
        isb();
        write_reg!("PMCCNTR_EL0", self.value);
        write_reg!("PMCCFILTR_EL0", self.filter);
        if !self.overflowed {
            // Only discard overflow generated by this scope, not old evidence.
            write_reg!("PMOVSCLR_EL0", CYCLE_BIT);
        }
        write_reg!("PMCR_EL0", self.pmcr);
        isb();
    }
}
